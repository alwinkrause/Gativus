def code(text):
    for line in text.rstrip("\n").split("\n"):
        p = P(stylename=_code)
        teletype.addTextToElement(p, line if line else " ")
        d._add(p)
    d.blank()


def T(rows, w):
    k = 6.5 / sum(w)
    d.table(rows, [round(x * k, 3) for x in w])


